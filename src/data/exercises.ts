export type ExerciseId = keyof typeof exerciseLibrary

export function getExercises(exerciseIds: ExerciseId[]) {
  return exerciseIds.map((exerciseId) => exerciseLibrary[exerciseId])
}

export function getAdventureEnergyLeaves(exercises: Exercise[]) {
  return exercises.reduce((sum, exercise) => sum + exercise.energyLeaves, 0)
}

export function getAdventureEstimatedMinutes(exercises: Exercise[]) {
  return exercises.reduce((sum, exercise) => sum + exercise.estimatedMinutes, 0)
}

export function getAdventureEstimatedTimeLabel(exercises: Exercise[]): LocalizedText {
  const estimatedMinutes = getAdventureEstimatedMinutes(exercises)

  return text(estimatedMinutes + ' min', estimatedMinutes + ' min')
}

export function getAdventureEquipment(exercises: Exercise[]): Equipment[] {
  const equipment = new Set<Equipment>()

  exercises.forEach((exercise) => {
    exercise.equipment.forEach((item) => {
      if (item !== 'none') {
        equipment.add(item)
      }
    })
  })

  return equipment.size > 0 ? Array.from(equipment) : ['none']
}
